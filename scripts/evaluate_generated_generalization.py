def tool(name, description):
    return {'type':'function','function':{'name':name,'description':description,'parameters':{'type':'object'}}}


def call(name, arguments, result, identity):
    return [dict(role='assistant',content=None,tool_calls=[dict(id=identity,type='function',
        function=dict(name=name,arguments=json.dumps(arguments)))]),
        dict(role='tool',tool_call_id=identity,content=result)]


def expression(text):
    return dict(role='assistant',content=text)


