const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const base=process.env.REVIEW_TEST_URL,id=process.env.REVIEW_INVESTIGATION_ID,output=process.env.REVIEW_OUTPUT_DIR;
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'}),errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1550,height:1000}});page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/investigate?saved='+id+'#ii-compare-rollout-cases');
  const section=page.locator('#ii-compare-rollout-cases');await section.locator('.case-group').first().waitFor();
  assert.equal(new URL(page.url()).hash,'#ii-compare-rollout-cases');
  assert.ok((await section.innerText()).includes('1 without a counterpart'));
  await page.getByRole('combobox',{name:'Rollout outcome filter'}).selectOption('improved');
  await page.waitForFunction(()=>document.querySelectorAll('.case-group').length===1);
  await section.getByRole('button',{name:'Compare evidence',exact:true}).click();
  const dialog=page.locator('.case-dialog');await dialog.locator('.case-unit').first().waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.case-column .case-unit').length>=20);
  assert.ok((await dialog.innerText()).includes('Reward: 0'));assert.ok((await dialog.innerText()).includes('Reward: 1'));
  assert.ok((await dialog.innerText()).includes('policy-0'));assert.ok((await dialog.innerText()).includes('policy-1'));
  await page.getByRole('combobox',{name:'Comparison observations'}).selectOption('recovery-evidence/1');
  await page.waitForFunction(()=>document.querySelector('[aria-label="Comparison cards"]')?.disabled===false);
  await dialog.locator('.case-path-shortcuts').first().getByRole('button',{name:/^Failed checks/}).click();
  await dialog.locator('.case-path').first().waitFor();
  assert.equal(await page.getByRole('combobox',{name:'Comparison cards'}).inputValue(),'failed-checks');
  assert.match(await dialog.locator('.case-path').first().innerText(),/linked attempts.*recorded checks:/);
  const pathUrl=await dialog.locator('.case-path a').first().getAttribute('href');
  await dialog.locator('.case-path a').first().click();
  await page.locator('.inspection-path-summary').waitFor();
  assert.equal(new URL(page.url()).searchParams.get('inspect_case'),new URL(pathUrl,base).searchParams.get('inspect_case'));
  assert.ok(await page.locator('.inspection-attempt').count()>2);
  assert.ok(await page.locator('.inspection-attempt-index button').count()>2);
  await page.getByRole('link',{name:/Back to/}).click();
  await page.locator('.case-dialog .case-path').first().waitFor();
  assert.equal(await page.getByRole('combobox',{name:'Comparison cards'}).inputValue(),'failed-checks');
  if(output)await page.screenshot({path:output+'/case-paths-desktop.png',fullPage:false});
  await page.reload();await page.locator('.case-dialog .case-path').first().waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.locator('.case-dialog-body').evaluate(n=>n.scrollWidth<=n.clientWidth+1),'Mobile path comparison overflow');
  if(output)await page.screenshot({path:output+'/case-paths-mobile.png',fullPage:false});
  await page.setViewportSize({width:1550,height:1000});
  await page.getByRole('combobox',{name:'Comparison cards'}).selectOption('all');
  assert.ok((await dialog.locator('.case-unit').count())>20);
  if(output)await page.screenshot({path:output+'/case-comparison-desktop.png',fullPage:false});
  const selected=new URL(page.url()).searchParams.get('case_selected');
  await dialog.locator('.case-unit a').first().click();
  await page.locator('#detail-title').waitFor();
  await page.getByRole('link',{name:/Back to/}).click();
  await page.locator('.case-dialog .case-unit').first().waitFor();
  assert.equal(new URL(page.url()).searchParams.get('case_selected'),selected);
  await page.reload();await page.locator('.case-dialog .case-unit').first().waitFor();
  assert.equal(await page.getByRole('combobox',{name:'Comparison observations'}).inputValue(),'recovery-evidence/1');
  assert.equal(await page.getByRole('combobox',{name:'Comparison cards'}).inputValue(),'all');
  assert.equal(await page.getByRole('combobox',{name:'Rollout outcome filter'}).inputValue(),'improved');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile page overflow');
  assert.ok(await page.locator('.case-dialog-body').evaluate(n=>n.scrollWidth<=n.clientWidth+1),'Mobile comparison overflow');
  if(output)await page.screenshot({path:output+'/case-comparison-mobile.png',fullPage:false});
  await page.locator('.case-dialog').getByRole('button',{name:'Close',exact:true}).click();
  await page.waitForFunction(()=>!new URL(location.href).searchParams.has('case_selected'));
  assert.equal(new URL(page.url()).searchParams.has('case_selected'),false);
  await page.getByRole('combobox',{name:'Rollout outcome filter'}).selectOption('unmatched');
  await page.waitForFunction(()=>document.querySelector('.case-group strong')?.textContent==='Different task');
  assert.equal(await section.getByRole('button',{name:'Compare evidence',exact:true}).isEnabled(),false);
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('Passed: frozen case groups, filters, reported outcomes, checkpoint context, both observation protocols, cards, map/back continuity, reload, unmatched cases and mobile layout.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
