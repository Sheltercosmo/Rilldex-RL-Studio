const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict'),fs=require('node:fs');
const base=process.env.REVIEW_TEST_URL,out=process.env.REVIEW_OUTPUT_DIR;
(async()=>{const browser=await chromium.launch({headless:true,channel:'msedge'}),errors=[];try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});page.on('pageerror',e=>errors.push(e.message));
 const fixture=JSON.parse(fs.readFileSync(out+'/browser-run.json','utf8'));
 await page.goto(base+'/connections?model_run='+fixture.run_id+'#model-section');
 await page.getByText('Pilot complete · plans and activities',{exact:true}).waitFor();
 const setup=page.locator('#model-continuous');await setup.locator('summary').click();
 assert.equal(await setup.getByLabel('Experiment',{exact:true}).inputValue(),'continuous-behavior-control');
 const code=setup.locator('pre');
 assert.ok((await code.innerText()).includes('--from-pilot'));
 assert.ok(!(await code.innerText()).includes('--decision-calls'));
 await setup.getByLabel('Worker decision calls',{exact:true}).fill('250');
 assert.ok((await code.innerText()).includes('--decision-calls 250'));
 await setup.getByLabel('Worker action',{exact:true}).selectOption('resume');
 assert.ok(!(await code.innerText()).includes('--from-pilot'));
 await setup.getByLabel('Worker action',{exact:true}).selectOption('refresh');
 assert.ok((await code.innerText()).includes('--refresh-worker'));
 await setup.getByLabel('Worker decision calls',{exact:true}).fill('');
 assert.ok(!(await code.innerText()).includes('--decision-calls'));
 if(out)await setup.screenshot({path:out+'/continuous-setup.png'});
 await page.setViewportSize({width:390,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 if(out)await setup.screenshot({path:out+'/continuous-mobile.png'});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+fixture.watch.dashboard_url);
 await page.locator('#monitor-grid').getByText('Reported execution errors',{exact:true}).waitFor({timeout:30000});
 const state=await page.request.get(base+'/api/monitoring?experiment=continuous-behavior-control').then(r=>r.json());
 const monitors=state.monitors.filter(m=>fixture.watch.monitors.includes(m.id));
 assert.equal(monitors.length,5);
 assert.ok(monitors.every(m=>m.observer===fixture.watch.observer));
 if(out)await page.locator('#monitor-grid').screenshot({path:out+'/continuous-measures.png'});
 const graph=await page.request.get(base+'/api/semantic-map/'+fixture.run_id+'?observer='+fixture.watch.observer).then(r=>r.json());
 assert.equal(graph.document.execution_returns.length,1);
 await page.goto(base+'/semantic-map?'+new URLSearchParams({run:fixture.run_id,observer:fixture.watch.observer,level:'plans'}));
 await page.locator('#plan-hierarchy').waitFor({state:'visible',timeout:30000});
 await page.getByRole('button',{name:/STEP 2.*Convert to PDF/s}).click();
 assert.ok((await page.locator('#plan-hierarchy').innerText()).includes('1 retry after reported error'));
 assert.deepEqual(errors,[]);
 const result={passed:true,installed:fixture.package.includes('site-packages'),published:fixture.watch.current_published,monitors:monitors.length,errors};
 fs.writeFileSync(out+'/browser-report.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1);});
