// Run after the execution smoke fixture and scripts/training_signals_fixture.py.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict'),fs=require('node:fs');
const base=process.env.REVIEW_TEST_URL,output=process.env.REVIEW_OUTPUT_DIR;
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'}),errors=[],checks=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/?view=execution&experiment=synthetic-execution-signals');
  await page.getByRole('link',{name:'Compare training runs →',exact:true}).click();
  const board=page.locator('#trainer-telemetry');
  const idle=()=>page.waitForFunction(()=>!document.querySelector('#trainer-telemetry').hasAttribute('aria-busy'));
  await board.getByRole('heading',{name:'Training signals',exact:true}).waitFor();
  await board.getByRole('combobox',{name:'Compare run',exact:true}).selectOption('synthetic-stable-control');
  await page.waitForFunction(()=>document.querySelectorAll('.telemetry-run-chip').length===2);
  await board.getByRole('combobox',{name:'Compare run',exact:true}).selectOption('synthetic-mismatch-growth');
  await page.waitForFunction(()=>document.querySelectorAll('.telemetry-run-chip').length===3);
  const outcome=board.locator('[data-signal-group=reward]'),mismatch=board.locator('[data-signal-group=mismatch]');
  assert.equal(await outcome.locator('.telemetry-raw').count(),3);
  assert.equal(await mismatch.locator('.telemetry-raw').count(),3);
  await board.getByRole('combobox',{name:'Trend',exact:true}).selectOption('10');
  await idle();
  await board.getByRole('combobox',{name:'Policy mismatch scale',exact:true}).selectOption('log');
  assert.equal(await outcome.locator('.telemetry-trend').count(),3);
  const before=await outcome.locator('.telemetry-trend').first().getAttribute('d');assert.ok(before);
  await board.getByRole('spinbutton',{name:'From step',exact:true}).fill('1020');
  await board.getByRole('spinbutton',{name:'To step',exact:true}).fill('1040');
  await board.getByRole('button',{name:'Select interval',exact:true}).click();
  await idle();
  assert.ok(await board.getByRole('button',{name:'Resume updates',exact:true}).isVisible());
  assert.equal(await outcome.locator('circle').count(),63);
  assert.equal(await mismatch.locator('circle').count(),63);
  assert.ok((await outcome.innerText()).includes('21/21 measured'));
  const grids=await board.locator('.telemetry-plot svg').evaluateAll(nodes=>nodes.map(n=>[n.dataset.min,n.dataset.max]));
  assert.ok(grids.every(([a,b])=>a==='1020'&&b==='1040'));
  const box=await outcome.locator('svg').boundingBox();await page.mouse.move(box.x+box.width*.5,box.y+50);
  assert.equal(await board.locator('.telemetry-cursor[visibility=visible]').count(),await board.locator('.telemetry-plot').count());
  checks.push('Three runs share colors, axis, selected interval and cursor; pause preserves displayed inputs');
  await board.locator('.telemetry-options > summary').click();
  await board.getByRole('button',{name:'Export comparison',exact:true}).click();
  const exports=page.getByRole('dialog',{name:'Export training signals'}),download=page.waitForEvent('download');
  await exports.getByRole('button',{name:'Download chart JSON',exact:true}).click();
  const contents=JSON.parse(fs.readFileSync(await (await download).path(),'utf8'));
  assert.equal(contents.datasets.length,3);assert.deepEqual(contents.selection.range,[1020,1040]);assert.equal(contents.selection.halfLife,10);
  await exports.getByRole('button',{name:'Close',exact:true}).click();
  await outcome.getByRole('button',{name:'Inspect updates',exact:true}).click();
  const interval=page.getByRole('dialog',{name:'Recorded updates in interval',exact:true});
  await interval.getByRole('button',{name:/learner_update 1025 ·/}).first().click();
  const detail=page.getByRole('dialog',{name:'Synthetic reward',exact:true});
  await detail.getByRole('heading',{name:'Linked rollout evidence',exact:true}).waitFor();
  assert.ok(await detail.locator('a[href^="/semantic-map"]').count()>=3);
  await detail.getByRole('button',{name:'Close',exact:true}).click();
  await interval.getByRole('button',{name:'Close',exact:true}).click();
  await page.reload();await board.getByRole('heading',{name:'Training signals',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.telemetry-run-chip').length===3);
  assert.equal(await board.getByRole('combobox',{name:'Trend',exact:true}).inputValue(),'10');
  assert.equal(await board.getByRole('spinbutton',{name:'From step',exact:true}).inputValue(),'1020');
  checks.push('Export retains the displayed snapshots and controls; interval updates open exact rollout evidence; URL restores selections');
  await board.getByRole('button',{name:'Full range',exact:true}).click();
  await idle();
  if(!await board.getByRole('combobox',{name:'Chart layout',exact:true}).isVisible())await board.locator('.telemetry-options > summary').click();
  await board.getByRole('combobox',{name:'Chart layout',exact:true}).selectOption('compact');
  await board.getByRole('combobox',{name:'Trend',exact:true}).scrollIntoViewIfNeeded();
  if(output)await page.screenshot({path:output+'/signals-comparison.png'});
  for(const width of [1024,390]){await page.setViewportSize({width,height:1000});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));}
  if(output)await page.screenshot({path:output+'/signals-mobile.png'});
  await board.getByRole('link',{name:'Capture settings',exact:true}).click();
  await page.getByRole('heading',{name:'Training signals',exact:true}).waitFor({state:'visible'});
  await page.getByText('Import existing trainer logs',{exact:true}).click();
  assert.ok(await page.getByText(/telemetry import trainer_state.json/).isVisible());
  await page.goto(base+'/connections#execution-section');
  await page.getByRole('heading',{name:'Execution & signals',exact:true}).waitFor({state:'visible'});
  checks.push('Desktop/mobile fit; setup links reveal the correct capture panel, live hook and batch import');
  await page.goto(base+'/?view=health&experiment=synthetic-stable-control');
  await board.locator('[data-signal-group=reward]').waitFor();
  assert.equal(await page.locator('#overview-context').isVisible(),false);
  assert.ok(await board.locator('.telemetry-raw').count()>=5);
  await page.route('**/api/trainer-telemetry/query?*',async route=>{
   const response=await route.fetch(),value=await response.json();
   const gap=value.series.find(s=>s.group==='mismatch');
   if(gap)value.series.push({...gap,id:'test-probability-tail',native_key:'test/p95',label:'Test probability tail',unit:'probability',definition:'Authored browser fixture for another selectable signal',points:gap.points.map(p=>({...p,value:p.value==null?null:p.value*2}))});
   await route.fulfill({response,json:value});
  });
  await page.reload();await board.getByRole('combobox',{name:'Add metric',exact:true}).selectOption('test-probability-tail');
  await board.getByRole('heading',{name:'Test probability tail',exact:true}).waitFor();
  assert.equal(await board.locator('[data-signal-group="extra/test-probability-tail"]').count(),1);
  await board.getByRole('button',{name:'Remove chart',exact:true}).click();
  assert.equal(await board.locator('[data-signal-group="extra/test-probability-tail"]').count(),0);
  await page.unroute('**/api/trainer-telemetry/query?*');
  await page.goto(base+'/?view=health&experiment=not-yet-recorded-demo');
  await board.getByText(/No native logs for this selection/).waitFor();
  assert.equal(await board.getByRole('link',{name:'Connect training data',exact:true}).getAttribute('href'),'/connections#telemetry-section');
  checks.push('Native-log-only and empty runs have usable entry paths; an extra same-category metric can be added and removed');
  assert.deepEqual(errors,[]);console.log(JSON.stringify({checks,errors},null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
