const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict'),fs=require('node:fs');
const base=process.env.REVIEW_TEST_URL,run=process.env.REVIEW_RUN_ID,out=process.env.REVIEW_OUTPUT_DIR;
(async()=>{const browser=await chromium.launch({headless:true,channel:'msedge'}),errors=[];try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/connections?model_run='+run+'#model-section');const panel=page.locator('#model-setup');
 await panel.getByRole('button',{name:'Inspect execution feedback',exact:true}).waitFor();
 const before=await page.request.get(base+'/api/models').then(r=>r.json());
 const used=before.pilot.usage.providers.jev.attempts,candidates=before.pilot.usage.providers.candidate.attempts;
 const originalMap=before.pilot.result.map_url;
 await panel.getByLabel('Decision calls',{exact:true}).fill(String(used+3));
 await panel.getByRole('button',{name:'Inspect execution feedback',exact:true}).click();
 await panel.getByText('Pilot · budget reached',{exact:true}).waitFor({timeout:30000});
 assert.ok((await panel.innerText()).includes('3 / 5 response pairs inspected · 2 pending · 1 reporting errors'));
 if(out)await panel.screenshot({path:out+'/feedback-partial.png'});
 await page.reload();await panel.getByText('Pilot · budget reached',{exact:true}).waitFor();
 assert.equal(await panel.getByLabel('Decision calls',{exact:true}).inputValue(),String(used+3));
 await panel.getByLabel('Decision calls',{exact:true}).fill(String(used+5));
 await panel.getByRole('button',{name:'Start / resume pilot',exact:true}).click();
 await panel.getByText('Pilot complete · plans and activities',{exact:true}).waitFor({timeout:30000});
 assert.ok((await panel.innerText()).includes('5 / 5 response pairs inspected · 0 pending · 1 reporting errors'));
 const state=await page.request.get(base+'/api/models').then(r=>r.json());
 assert.equal(state.pilot.usage.providers.candidate.attempts,candidates);
 assert.equal(state.pilot.usage.providers.jev.attempts,used+5);
 await page.setViewportSize({width:390,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 if(out)await panel.screenshot({path:out+'/feedback-complete-mobile.png'});
 await page.setViewportSize({width:1440,height:1000});
 await panel.getByRole('link',{name:'Open plans & attempts →'}).click();
 await page.locator('#plan-hierarchy').waitFor({state:'visible',timeout:30000});
 await page.getByRole('button',{name:/STEP 2.*Convert to PDF/s}).click();
 const text=await page.locator('#plan-hierarchy').innerText();
 assert.ok(text.includes('ERROR: converter unavailable'));assert.ok(text.includes('PDF written'));
 assert.ok(text.includes('1 retry after reported error'));
 const map=await page.request.get(base+'/api/semantic-map/'+run+'?'+new URL(page.url()).searchParams).then(r=>r.json());
 assert.equal(map.document.execution_returns.length,1);
 assert.equal(map.document.execution_reports.observations.filter(r=>r.error==='reported').length,1);
 const old=await page.request.get(base+'/api/semantic-map/'+run+'?'+new URL(base+originalMap).searchParams).then(r=>r.json());
 assert.equal(old.available,true);assert.equal(old.document.execution_reports,undefined);
 if(out)await page.locator('#plan-hierarchy').screenshot({path:out+'/feedback-return-path.png'});
 assert.deepEqual(errors,[]);
 const report={passed:true,installed:true,new_candidate_calls:0,new_authored_decisions:5,errors,
  checks:['upgrade existing pilot','partial feedback coverage','reload and resume','shared lifetime limit','mobile overflow','return after error path','stored error text excluded','earlier map preserved']};
 if(out)fs.writeFileSync(out+'/browser-report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1);});
