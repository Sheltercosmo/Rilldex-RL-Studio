const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict'),fs=require('node:fs');
const base=process.env.REVIEW_TEST_URL,out=process.env.REVIEW_OUTPUT_DIR;
(async()=>{const browser=await chromium.launch({headless:true,channel:'msedge'}),errors=[];try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});page.on('pageerror',e=>errors.push(e.message));
 const fixture=JSON.parse(fs.readFileSync(out+'/browser-run.json','utf8'));
 await page.goto(base+'/connections?model_run='+fixture.run_id+'#model-section');const panel=page.locator('#model-setup');
 await panel.getByRole('button',{name:'Compare approaches',exact:true}).waitFor();
 const before=await page.request.get(base+'/api/models').then(r=>r.json());
 const used=before.pilot.usage.providers.jev.attempts,candidates=before.pilot.usage.providers.candidate.attempts;
 await panel.getByLabel('Decision calls',{exact:true}).fill(String(used+1));
 await panel.getByRole('button',{name:'Compare approaches',exact:true}).click();
 await panel.getByText('Pilot · budget reached',{exact:true}).waitFor({timeout:30000});
 assert.ok((await panel.innerText()).includes('0 / 1 repeat pairs inspected · 1 pending'));
 await panel.screenshot({path:out+'/approaches-partial.png'});
 await page.reload();await panel.getByText('Pilot · budget reached',{exact:true}).waitFor();
 assert.equal(await panel.getByLabel('Decision calls',{exact:true}).inputValue(),String(used+1));
 await panel.getByLabel('Decision calls',{exact:true}).fill(String(used+2));
 await panel.getByRole('button',{name:'Start / resume pilot',exact:true}).click();
 await panel.getByText('Pilot complete · plans and activities',{exact:true}).waitFor({timeout:30000});
 assert.ok((await panel.innerText()).includes('1 / 1 repeat pairs inspected · 0 pending'));
 const state=await page.request.get(base+'/api/models').then(r=>r.json());
 assert.equal(state.pilot.usage.providers.candidate.attempts,candidates);
 assert.equal(state.pilot.usage.providers.jev.attempts,used+2);
 await page.setViewportSize({width:390,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await panel.screenshot({path:out+'/approaches-mobile.png'});
 await page.setViewportSize({width:1440,height:1000});
 await panel.getByRole('link',{name:'Review approach comparisons →',exact:true}).click();
 await page.locator('.wr-target').first().waitFor({state:'visible',timeout:30000});
 const map=await page.request.get(base+'/api/semantic-map/'+fixture.run_id+'?'+new URL(page.url()).searchParams).then(r=>r.json());
 assert.equal(map.document.method_comparison.schema,'work-method-comparison/4');
 assert.equal(map.document.method_comparison.observations[0].comparison,'alternative_procedure');
 const old=await page.request.get(base+'/api/semantic-map/'+fixture.run_id+'?'+new URL(base+fixture.original_map).searchParams).then(r=>r.json());
 assert.equal(old.available,true);assert.equal(old.document.method_comparison,undefined);
 await page.locator('.wr-target').first().getByText('1/1 procedure comparisons established · 1 changed',{exact:true}).waitFor({timeout:30000});
 await page.locator('.wr-target').first().click();
 await page.locator('.wr-sequence .wr-procedure').getByText('Different procedure',{exact:true}).waitFor();
 await page.locator('.wr-sequence').screenshot({path:out+'/approaches-work-path.png'});
 assert.deepEqual(errors,[]);
 const report={passed:true,installed:true,new_candidate_calls:0,new_authored_decisions:2,errors,
  checks:['upgrade existing pilot','native dispatch evidence','two-stage budget pause','reload and resume','mobile layout','work-map comparison','earlier map preserved']};
 fs.writeFileSync(out+'/browser-report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1);});
