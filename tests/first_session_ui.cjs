const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const base=process.env.REVIEW_TEST_URL,output=process.env.REVIEW_OUTPUT_DIR;
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'}),errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByRole('button',{name:/Open an example/}).waitFor();
  assert.equal(await page.locator('#add-monitor').isVisible(),false);
  assert.equal(await page.locator('#trainer-telemetry').isVisible(),false);
  if(output)await page.screenshot({path:output+'/empty-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:900});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  if(output)await page.screenshot({path:output+'/empty-mobile.png',fullPage:true});
  await page.getByRole('button',{name:/Open an example/}).click();
  await page.locator('.example-finding').waitFor();
  assert.ok(await page.getByRole('heading',{name:'Inspect a rollout'}).isVisible());
  assert.equal(await page.locator('.workspace-empty').count(),0);
  await page.setViewportSize({width:1440,height:1000});
  if(output)await page.screenshot({path:output+'/example.png',fullPage:true});
  const scope=new URL(page.url()).searchParams.get('experiment');
  const data=await page.request.get(base+'/api/monitoring?experiment='+encodeURIComponent(scope)).then(r=>r.json());
  const rid=data.runs[0].id;
  await page.goto(base+'/connections?model_run='+rid+'#model-section');
  await page.getByRole('heading',{name:'Models & observation'}).waitFor();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Pilot rollout"]')?.value);
  assert.equal(await page.getByRole('combobox',{name:'Pilot rollout'}).inputValue(),rid);
  await page.getByText('Configure models or run from code',{exact:true}).click();
  await page.getByRole('combobox',{name:'Setup shell'}).selectOption('powershell');
  assert.ok((await page.locator('#model-setup').innerText()).includes('python -m rilldex.models pilot'));
  if(output)await page.screenshot({path:output+'/models.png',fullPage:true});
  await page.setViewportSize({width:390,height:900});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Model setup mobile overflow');
  await page.goto(base+'/connections#snapshot-section');
  await page.locator('#upload-files').setInputFiles({name:'example-import.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({trajectory_format:'generation/1',prompt:'1+1',completion:'2',metadata:{experiment:'Imported example'},outcome:{reward:1}}))});
  await page.locator('#import-snapshot').click();
  await page.locator('#import-links .feature-readiness').waitFor();
  assert.ok((await page.locator('#import-links').innerText()).includes('1 rollouts available'));
  assert.ok((await page.locator('#import-links').innerText()).includes('Run a bounded model pilot'));
  await page.locator('#import-links').getByRole('link',{name:'Source inspection →',exact:true}).click();
  await page.locator('#map-availability').getByRole('link',{name:'Set up semantic analysis →'}).waitFor();
  const selected=new URL(page.url()).searchParams.get('run');
  await page.getByRole('link',{name:'Set up semantic analysis →'}).click();
  await page.waitForFunction(id=>document.querySelector('[aria-label="Pilot rollout"]')?.value===id,selected);
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('Passed: empty onboarding, example receipt and source links, desktop/mobile layouts, model route, import readiness.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
